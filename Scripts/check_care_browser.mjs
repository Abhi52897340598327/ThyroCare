#!/usr/bin/env node
// Uses synthetic localhost accounts only. Install Playwright in /tmp/thyrocare-browser first.
import { createRequire } from 'node:module';
import { spawn, spawnSync } from 'node:child_process';
import { mkdtemp, symlink, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH ?? '/tmp/thyrocare-browser/node_modules/playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'docs', 'qa');
await mkdir(output, { recursive:true });
const temp = await mkdtemp(path.join(tmpdir(), 'thyrocare-browser-'));
await symlink(path.join(root, 'Backend/Dashboard/out'), path.join(temp, 'Public'));
const port = await new Promise(resolve => { const s = net.createServer(); s.listen(0,'127.0.0.1',()=>{ const p = s.address().port; s.close(()=>resolve(p)); }); });
const base = `http://localhost:${port}`;
const password = 'Synthetic-' + crypto.randomUUID();
const env = { ...process.env, HOST:'127.0.0.1', PORT:String(port), CARE_WEB_ORIGIN:base, CARE_DATA_DIRECTORY:path.join(temp,'CareData') };
const binary = path.join(root,'Backend/.build/debug/Run');
const provision = spawnSync(binary, [], { cwd:temp, env:{...env, CARE_PROVISION_CLINICIAN:'1',CARE_CLINICIAN_EMAIL:'clinician@example.test',CARE_CLINICIAN_NAME:'Synthetic Clinician',CARE_CLINICIAN_PASSWORD:password}, encoding:'utf8' });
if (provision.status !== 0) throw new Error('Synthetic clinician provisioning failed');
let server;
async function start() {
    server = spawn(binary,[],{cwd:temp,env,stdio:'ignore'});
    for (let i=0;i<100;i++) { try { if ((await fetch(base+'/health')).ok) return; } catch {} await new Promise(r=>setTimeout(r,100)); }
    throw new Error('Local test backend did not start');
}
async function stop() { if (!server || server.exitCode !== null) return; await new Promise(resolve=>{server.once('exit',resolve);server.kill('SIGTERM');}); }
let browser;
const checks=[];
function checked(message) { checks.push(message); console.log(message); }
try {
    await start();
    browser = await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
    const patientContext = await browser.newContext({viewport:{width:1440,height:1000}});
    const clinicianContext = await browser.newContext({viewport:{width:1440,height:1000}});
    const patient = await patientContext.newPage(), clinician = await clinicianContext.newPage();
    await patient.goto(base+'/patient');
    await patient.getByRole('button',{name:'Create patient account',exact:true}).click();
    await patient.getByLabel('Name',{exact:true}).fill('Synthetic Patient');
    await patient.getByLabel('Email',{exact:true}).fill('patient@example.test');
    await patient.getByLabel('Password',{exact:true}).fill(password);
    await patient.getByRole('button',{name:'Create account',exact:true}).click();
    await patient.getByRole('heading',{name:'Synthetic Patient',exact:true}).waitFor();
    const me = await (await patientContext.request.get(base+'/v1/me')).json();
    await clinician.goto(base+'/clinician');
    await clinician.getByLabel('Email',{exact:true}).fill('clinician@example.test');
    await clinician.getByLabel('Password',{exact:true}).fill(password);
    await clinician.getByRole('button',{name:'Sign in',exact:true}).click();
    await clinician.getByRole('button',{name:'Create 15-minute invitation'}).click();
    const invitation = await clinician.locator('code').innerText();
    await patient.getByLabel('Invitation code',{exact:true}).fill(invitation);
    await patient.getByRole('button',{name:'Review invitation',exact:true}).click();
    await patient.getByRole('button',{name:'Confirm connection',exact:true}).click();
    await clinician.reload();
    await clinician.getByRole('button',{name:'Synthetic Patient',exact:true}).click();
    checked('Distinct authenticated patient and clinician browsers linked by reviewed invitation');
    await patient.getByRole('button',{name:'Add record',exact:true}).click();
    const lab = patient.locator('form');
    await lab.getByLabel('Analyte',{exact:false}).selectOption('Free T4');
    await lab.getByLabel(/Result \(preserve/).fill('<0.01');
    await lab.getByLabel(/Laboratory \/ report source/).fill('Synthetic report');
    await lab.getByLabel(/Result received/).fill('2026-10-22');
    await lab.getByRole('button',{name:'Save record',exact:true}).click();
    await patient.getByRole('heading',{name:'Free T4',exact:true}).waitFor().catch(async error => { console.error(await patient.locator('body').innerText()); throw error; });
    checked('Censored lab saved without invented collection date or reference interval');
    await patient.getByRole('navigation').getByRole('button',{name:'Messages',exact:true}).click();
    await patient.getByRole('button',{name:'Add record',exact:true}).click();
    await patient.locator('form textarea').fill('I received my Free T4 result today');
    await patient.getByRole('button',{name:'Save record',exact:true}).click();
    await clinician.getByRole('navigation').getByRole('button',{name:'Messages',exact:true}).click();
    await clinician.getByRole('button',{name:'Refresh',exact:true}).click();
    await clinician.getByText('I received my Free T4 result today',{exact:true}).waitFor();
    await clinician.getByRole('button',{name:'Add record',exact:true}).click();
    await clinician.locator('form textarea').fill('Please confirm the collection date from your report.');
    await clinician.getByRole('button',{name:'Save record',exact:true}).click();
    await patient.getByRole('button',{name:'Refresh',exact:true}).click();
    await patient.getByText('Please confirm the collection date from your report.',{exact:true}).waitFor();
    checked('Identical two-way message visible in separate browser sessions');
    await clinician.locator('form').waitFor({state:'detached'});
    await clinician.getByRole('navigation').getByRole('button',{name:'Shared notes',exact:true}).click();
    await clinician.getByRole('button',{name:'Add record',exact:true}).click();
    await clinician.locator('form textarea').fill('Synthetic shared care note. No treatment change is recorded.');
    await clinician.locator('form').getByLabel('State',{exact:true}).selectOption('signed');
    await clinician.getByRole('button',{name:'Save record',exact:true}).click();
    await clinician.locator('form').waitFor({state:'detached'});
    await patient.getByRole('navigation').getByRole('button',{name:'Shared notes',exact:true}).click();
    await patient.getByRole('button',{name:'Refresh',exact:true}).click();
    await patient.getByText('Synthetic shared care note. No treatment change is recorded.',{exact:true}).waitFor();
    checked('Signed clinician note visible to patient');
    await patient.screenshot({path:path.join(output,'patient-shared-note-desktop.png'),fullPage:true});
    await patient.setViewportSize({width:390,height:844});
    await patient.emulateMedia({reducedMotion:'reduce'});
    await patient.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const navigationToggle = patient.getByRole('button', {name:'Shared notes · Change section',exact:true});
    await navigationToggle.click();
    await patient.getByRole('navigation').getByRole('button',{name:'Shared notes',exact:true}).click();
    assert.equal(await patient.getByRole('navigation').isVisible(), false);
    assert.ok(await patient.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
    await patient.screenshot({path:path.join(output,'patient-shared-note-mobile.png'),fullPage:true});
    await patient.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
    await patient.screenshot({path:path.join(output,'patient-shared-note-dark.png'),fullPage:true});
    checked('390 px viewport without document-level horizontal overflow; dark/reduced-motion screenshots captured');
    await patient.setViewportSize({width:1440,height:1000});
    await stop(); await start();
    await patient.reload();
    await patient.getByRole('navigation').getByRole('button',{name:'Messages',exact:true}).click();
    await patient.getByText('Please confirm the collection date from your report.',{exact:true}).waitFor();
    checked('Browser session and identical records survive backend process restart and refresh');
    const b = await browser.newContext();
    const registration = await b.request.post(base+'/v1/auth/register',{data:{email:'other@example.test',name:'Synthetic Other',password}});
    assert.equal(registration.status(),200);
    assert.equal((await b.request.get(base+`/v1/patients/${me.id}/labs`)).status(),403);
    checked('Second patient cannot fetch first patient records by altering ID');
    await writeFile(path.join(output,'browser-result.json'),JSON.stringify({status:'passed',checks,scope:'Local Chrome with synthetic accounts; native messaging, VoiceOver and device notifications not verified'},null,2)+'\n');

} finally { await browser?.close(); await stop(); await rm(temp,{recursive:true,force:true}); }
